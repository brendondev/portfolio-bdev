// Language Toggle
function initLanguage() {
  const savedLang = localStorage.getItem('lang') || 'pt';
  const langBtns = document.querySelectorAll('.lang-btn');
  
  function setLanguage(lang) {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (translations[lang] && translations[lang][key]) {
        el.textContent = translations[lang][key];
      }
    });
    
    langBtns.forEach(btn => {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });
    
    localStorage.setItem('lang', lang);
  }
  
  langBtns.forEach(btn => {
    btn.addEventListener('click', function(e) {
      e.preventDefault();
      setLanguage(this.getAttribute('data-lang'));
    });
  });
  
  setLanguage(savedLang);
}

// Modal Functions
function openModal(projectId) {
  const modal = document.getElementById('modal-' + projectId);
  if (modal) {
    modal.classList.add('active');
    document.body.style.overflow = 'hidden';
  }
}

function closeModal(projectId) {
  const modal = document.getElementById('modal-' + projectId);
  if (modal) {
    modal.classList.remove('active');
    document.body.style.overflow = '';
  }
}

// Load Blog Posts from Dev.to API
async function loadBlogPosts() {
  const container = document.getElementById('blog-posts');
  if (!container) return;
  
  const currentLang = localStorage.getItem('lang') || 'pt';
  const blogTitle = currentLang === 'pt' ? 'Artigos' : 'Writing';
  const blogSubtitle = currentLang === 'pt' ? 'Meus artigos no Dev.to:' : 'My articles on Dev.to:';
  const blogLink = currentLang === 'pt' ? 'Ver posts no Dev.to →' : 'View posts on Dev.to →';
  const blogAuto = currentLang === 'pt' ? 'Posts também aparecem aqui automaticamente' : 'Posts also appear here automatically';
  const readTime = currentLang === 'pt' ? 'min de leitura' : 'min read';
  
  container.innerHTML = `
    <div class="bento-card" style="grid-column: span 2; text-align: center; color: var(--text-secondary);">
      <p style="margin-bottom: 12px;">📝 ${blogTitle}</p>
      <p style="font-size: 0.875rem; margin-bottom: 12px;">${blogSubtitle}</p>
      <a href="https://dev.to/brendondev" target="_blank" style="color: var(--accent); font-weight: 600;">
        ${blogLink}
      </a>
      <p style="font-size: 0.75rem; margin-top: 16px; color: var(--text-muted);">
        ${blogAuto}
      </p>
    </div>
  `;
  
  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 5000);
    
    const response = await fetch('https://dev.to/api/articles?username=brendondev', {
      signal: controller.signal
    });
    
    clearTimeout(timeout);
    
    if (!response.ok) throw new Error('API error');
    
    const posts = await response.json();
    
    if (posts && posts.length > 0) {
      container.innerHTML = posts.slice(0, 4).map(post => `
        <a href="${post.url}" target="_blank" class="thought-bento-card bento-card">
          ${post.cover_image ? `<img src="${post.cover_image}" alt="${post.title}" class="post-cover-image" onerror="this.parentElement.classList.add('no-image')">` : ''}
          <div class="post-content-wrapper">
            <div class="date">${new Date(post.published_at).toLocaleDateString(currentLang === 'pt' ? 'pt-BR' : 'en-US', { day: '2-digit', month: 'short', year: 'numeric' })}</div>
            <h3>${post.title}</h3>
            <p class="read-time">${post.reading_time_minutes} ${readTime}</p>
          </div>
        </a>
      `).join('');
    }
  } catch (error) {
    console.log('Blog posts will show link fallback');
  }
}

// Main Initialization
document.addEventListener('DOMContentLoaded', function() {
  // Initialize Language
  initLanguage();
  
  // Theme Toggle
  const themeToggle = document.getElementById('themeToggle');
  if (themeToggle) {
    const savedTheme = localStorage.getItem('theme');
    const prefersDark = window.matchMedia('(prefers-color-scheme: dark)').matches;
    let isDark = savedTheme ? savedTheme === 'dark' : prefersDark;
    
    document.documentElement.setAttribute('data-theme', isDark ? 'dark' : 'light');
    themeToggle.textContent = isDark ? '☀️' : '🌙';
    
    themeToggle.onclick = function() {
      isDark = !isDark;
      document.documentElement.setAttribute('data-theme', isDark ? 'dark' : 'light');
      localStorage.setItem('theme', isDark ? 'dark' : 'light');
      themeToggle.textContent = isDark ? '☀️' : '🌙';
    };
  }
  
  // Navigation Active State
  const navLinks = document.querySelectorAll('.nav-links a');
  const sections = document.querySelectorAll('section[id]');
  
  function updateActiveNav() {
    const scrollPos = window.scrollY + 120;
    
    sections.forEach(section => {
      const sectionTop = section.offsetTop;
      const sectionHeight = section.offsetHeight;
      const sectionId = section.getAttribute('id');
      
      if (scrollPos >= sectionTop && scrollPos < sectionTop + sectionHeight) {
        navLinks.forEach(link => {
          link.classList.remove('active');
          if (link.getAttribute('href') === '#' + sectionId) {
            link.classList.add('active');
          }
        });
      }
    });
  }
  
  window.addEventListener('scroll', updateActiveNav);
  updateActiveNav();
  
  // Smooth Scroll
  document.querySelectorAll('a[href^="#"]').forEach(anchor => {
    anchor.addEventListener('click', function(e) {
      e.preventDefault();
      const targetId = this.getAttribute('href');
      if (targetId === '#') return;
      
      const target = document.querySelector(targetId);
      if (target) {
        target.scrollIntoView({ behavior: 'smooth' });
      }
    });
  });
  
  // Back to Top Button
  const backToTopBtn = document.getElementById('backToTop');
  if (backToTopBtn) {
    window.addEventListener('scroll', function() {
      if (window.scrollY > 500) {
        backToTopBtn.classList.add('visible');
      } else {
        backToTopBtn.classList.remove('visible');
      }
    });
    
    backToTopBtn.addEventListener('click', function() {
      window.scrollTo({ top: 0, behavior: 'smooth' });
    });
  }
  
  // Form Submission - Netlify AJAX with Local CAPTCHA
  const contactForm = document.getElementById('contactForm');
  if (contactForm) {
    // Generate math captcha on load
    const num1 = Math.floor(Math.random() * 10) + 1;
    const num2 = Math.floor(Math.random() * 10) + 1;
    const correctAnswer = num1 + num2;
    
    // Store answer and timestamp
    sessionStorage.setItem('captcha_answer', correctAnswer);
    document.getElementById('form-timestamp').value = Date.now();
    
    // Set question text
    const currentLang = localStorage.getItem('lang') || 'pt';
    const t = translations[currentLang] || translations.pt;
    const questionLabel = document.getElementById('captcha-question');
    if (questionLabel) {
      questionLabel.textContent = `${t.form_captcha}${num1} + ${num2}${t.form_captcha_suffix}`;
    }
    
    contactForm.addEventListener('submit', function(e) {
      e.preventDefault();
      
      const submitBtn = this.querySelector('.submit-btn');
      const lang = localStorage.getItem('lang') || 'pt';
      const trans = translations[lang] || translations.pt;
      const originalText = trans.form_send;
      const sendingText = lang === 'pt' ? 'Enviando...' : 'Sending...';
      
      // Validate CAPTCHA
      const userAnswer = parseInt(document.getElementById('captcha-answer')?.value) || 0;
      const storedAnswer = parseInt(sessionStorage.getItem('captcha_answer')) || 0;
      
      if (userAnswer !== storedAnswer) {
        showToast('error', lang === 'pt' ? 'Resposta incorreta. Tente novamente.' : 'Incorrect answer. Please try again.');
        
        // Regenerate captcha
        const newNum1 = Math.floor(Math.random() * 10) + 1;
        const newNum2 = Math.floor(Math.random() * 10) + 1;
        sessionStorage.setItem('captcha_answer', newNum1 + newNum2);
        if (questionLabel) {
          questionLabel.textContent = `${trans.form_captcha}${newNum1} + ${newNum2}${trans.form_captcha_suffix}`;
        }
        document.getElementById('captcha-answer').value = '';
        return;
      }
      
      // Validate time (minimum 3 seconds to fill form)
      const submitTime = Date.now();
      const startTime = parseInt(document.getElementById('form-timestamp').value) || 0;
      const timeDiff = submitTime - startTime;
      
      if (timeDiff < 3000) {
        showToast('error', lang === 'pt' ? 'Preencha o formulário mais devagar.' : 'Please fill out the form more slowly.');
        return;
      }
      
      // Check honeypot
      const honeypot = document.querySelector('[name="bot-field"]');
      if (honeypot && honeypot.value !== '') {
        showToast('error', lang === 'pt' ? 'Erro de validação.' : 'Validation error.');
        return;
      }
      
      if (submitBtn) {
        submitBtn.textContent = sendingText;
        submitBtn.disabled = true;
      }
      
      const formData = new FormData(this);
      const data = {};
      formData.forEach((value, key) => {
        if (key !== 'bot-field' && key !== 'captcha_answer') {
          data[key] = value;
        }
      });
      
      fetch("/", {
        method: "POST",
        headers: { "Content-Type": "application/x-www-form-urlencoded" },
        body: new URLSearchParams(data).toString()
      })
      .then(response => {
        if (response.ok) {
          showToast('success', lang === 'pt' ? 'Mensagem enviada com sucesso!' : 'Message sent successfully!');
          this.reset();
          
          // Regenerate captcha
          const newNum1 = Math.floor(Math.random() * 10) + 1;
          const newNum2 = Math.floor(Math.random() * 10) + 1;
          sessionStorage.setItem('captcha_answer', newNum1 + newNum2);
          if (questionLabel) {
            questionLabel.textContent = `${trans.form_captcha}${newNum1} + ${newNum2}${trans.form_captcha_suffix}`;
          }
          document.getElementById('form-timestamp').value = Date.now();
          document.getElementById('captcha-answer').value = '';
        } else {
          throw new Error('Failed');
        }
      })
      .catch(error => {
        showToast('error', lang === 'pt' ? 'Erro ao enviar. Tente novamente.' : 'Error sending. Please try again.');
      })
      .finally(() => {
        if (submitBtn) {
          submitBtn.textContent = originalText;
          submitBtn.disabled = false;
        }
      });
    });
  }
  
  // Toast notification function
  function showToast(type, message) {
    const container = document.getElementById('toast-container');
    if (!container) return;
    
    const toast = document.createElement('div');
    toast.className = `toast ${type}`;
    
    const icon = type === 'success' ? '✓' : '✕';
    const iconEmoji = type === 'success' ? '✅' : '❌';
    
    toast.innerHTML = `
      <span class="toast-icon">${iconEmoji}</span>
      <span class="toast-message">${message}</span>
    `;
    
    container.appendChild(toast);
    
    setTimeout(() => {
      toast.remove();
    }, 3000);
  }
  
  // Modal click handlers
  const modalTriggers = document.querySelectorAll('.project-modal-trigger');
  modalTriggers.forEach(trigger => {
    trigger.addEventListener('click', function() {
      const projectId = this.getAttribute('data-project');
      openModal(projectId);
    });
  });
  
  // Close modal on background click
  document.querySelectorAll('.modal-overlay').forEach(modal => {
    modal.addEventListener('click', function(e) {
      if (e.target === this) {
        const projectId = this.id.replace('modal-', '');
        closeModal(projectId);
      }
    });
  });
  
  // Close modal on Escape key
  document.addEventListener('keydown', function(e) {
    if (e.key === 'Escape') {
      document.querySelectorAll('.modal-overlay.active').forEach(modal => {
        const projectId = modal.id.replace('modal-', '');
        closeModal(projectId);
      });
    }
  });
  
  // Load Blog Posts
  loadBlogPosts();
});
